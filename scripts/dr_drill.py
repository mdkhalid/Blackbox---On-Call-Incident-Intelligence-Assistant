"""Failover and restore drill with measured RTO/RPO.

Usage:
    python scripts/dr_drill.py --write

The SQLite harness models the control-plane steps (stop writes, promote, repoint) and
measures how long the promoted target takes to serve its first read and accept a
canary write. Against Postgres, use `blackbox.ops.drills.simulate_failover` with a
`promote` callable and pass the real endpoints; the measurement code is the same.

Results are written to `docs/dr-drill-results.md` only with `--write`.
"""
from __future__ import annotations

import argparse
import json
from datetime import UTC, datetime
from pathlib import Path


def _render(results: list, stamp: str) -> str:
    lines = [
        "# DR Drill Results",
        "",
        "Generated by `scripts/dr_drill.py`. These numbers come from a local drill",
        "harness (SQLite file copy as the promotion step), not from a production",
        "region failover; the harness proves the measurement and the procedure, and the",
        "same code measures a real promotion given live endpoints.",
        "",
        f"- Run at: {stamp}",
        "",
        "| Drill | Topology | RTO (s) | RPO (rows) | Rows before | Rows after |",
        "|---|---|---|---|---|---|",
    ]
    for result in results:
        d = result.to_dict()
        lines.append(
            f"| {d['name']} | {d['topology']} | {d['rto_s']} | {d['rpo_rows']} | "
            f"{d['rows_before']} | {d['rows_after']} |"
        )
    lines += ["", "Notes:"]
    for result in results:
        for note in result.notes:
            lines.append(f"- {result.name}: {note}")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--work-dir", default="data/dr", help="scratch directory for drill databases")
    parser.add_argument("--conversations", type=int, default=20)
    parser.add_argument("--tenant", default="default")
    parser.add_argument("--write", action="store_true", help="write docs/dr-drill-results.md")
    args = parser.parse_args(argv)

    from blackbox.ops.drills import make_backup, measure_restore, simulate_failover

    work = Path(args.work_dir)
    work.mkdir(parents=True, exist_ok=True)
    for name in ("primary.db", "replica.db", "backup.db", "restored.db"):
        (work / name).unlink(missing_ok=True)

    primary_url = f"sqlite:///{(work / 'primary.db').as_posix()}"
    replica_url = f"sqlite:///{(work / 'replica.db').as_posix()}"

    failover = simulate_failover(
        source_url=primary_url,
        target_url=replica_url,
        conversations=args.conversations,
        tenant_id=args.tenant,
    )

    backup = work / "backup.db"
    make_backup(primary_url, backup)
    restore = measure_restore(
        source_url=primary_url,
        backup_path=backup,
        restored_url=f"sqlite:///{(work / 'restored.db').as_posix()}",
        tenant_id=args.tenant,
    )

    results = [failover, restore]
    payload = {
        "run_at": datetime.now(UTC).isoformat(),
        "results": [result.to_dict() for result in results],
    }
    if args.write:
        out = Path("docs/dr-drill-results.md")
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(_render(results, payload["run_at"]), encoding="utf-8")
        payload["written_to"] = str(out)
    print(json.dumps(payload, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
